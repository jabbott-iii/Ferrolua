//! Runs `cargo xtask fuzz` in a small workspace whose `lunaferra-fuzz` prints its arguments and
//! exits with status 3, and checks that the task passes the arguments on and exits with the same
//! status. The fuzzer's own behavior is tested in `fuzz/tests/`. The workspace is in a folder of
//! its own under the target folder, so its build never touches Lunaferra's.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

/// The files of the workspace, with a `lunaferra-fuzz` that stands in for the fuzzer.
const WORKSPACE: [(&str, &str); 4] = [
    (
        "Cargo.toml",
        "[workspace]\nresolver = \"3\"\nmembers = [\"fuzz\"]\n",
    ),
    (
        "Cargo.lock",
        "# This file is automatically @generated by Cargo.\n\
         # It is not intended for manual editing.\n\
         version = 4\n\n\
         [[package]]\nname = \"lunaferra-fuzz\"\nversion = \"0.0.0\"\n",
    ),
    (
        "fuzz/Cargo.toml",
        "[package]\nname = \"lunaferra-fuzz\"\nversion = \"0.0.0\"\nedition = \"2024\"\n",
    ),
    (
        "fuzz/src/main.rs",
        "fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    println!(\"{}\", args.join(\" \"));
    std::process::exit(3);
}
",
    ),
];

/// Writes the workspace into a folder named `name`, and returns the folder.
fn workspace(name: &str) -> PathBuf {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join("fuzz")
        .join(name);
    if dir.exists() {
        fs::remove_dir_all(&dir).expect("the folder of an earlier run can be removed");
    }
    for (path, text) in WORKSPACE {
        let path = dir.join(path);
        fs::create_dir_all(path.parent().expect("a file is in a folder"))
            .expect("the file's folder can be made");
        fs::write(path, text).expect("the file can be written");
    }
    dir
}

/// A `cargo xtask fuzz` command with `args`, run in `dir`.
fn fuzz(dir: &Path, args: &[&str]) -> Command {
    let mut command = Command::new(env!("CARGO_BIN_EXE_xtask"));
    command
        .arg("fuzz")
        .args(args)
        .current_dir(dir)
        .env("CARGO_TARGET_DIR", dir.join("target"));
    command
}

fn run(command: &mut Command) -> Output {
    command.output().expect("`cargo xtask` runs")
}

fn stdout(output: &Output) -> &str {
    std::str::from_utf8(&output.stdout).expect("the output is UTF-8")
}

#[test]
fn runs_the_fuzzer_with_the_arguments_after_fuzz_and_exits_with_its_status() {
    let dir = workspace("passes-arguments");
    let output = run(&mut fuzz(&dir, &["fixture-panic", "--seed", "7"]));
    assert_eq!(stdout(&output), "fixture-panic --seed 7\n");
    assert_eq!(output.status.code(), Some(3));
}

#[test]
fn runs_the_fuzzer_with_no_arguments() {
    let dir = workspace("no-arguments");
    let output = run(&mut fuzz(&dir, &[]));
    assert_eq!(stdout(&output), "\n");
    assert_eq!(output.status.code(), Some(3));
}

#[test]
fn finds_cargo_on_the_path_when_cargo_is_not_set() {
    let dir = workspace("cargo-on-path");
    let output = run(fuzz(&dir, &["fixture-hang"]).env_remove("CARGO"));
    assert_eq!(stdout(&output), "fixture-hang\n");
    assert_eq!(output.status.code(), Some(3));
}

#[test]
fn fails_when_cargo_cannot_start() {
    let dir = workspace("no-cargo");
    let cargo = dir.join("no-such-cargo");
    let source = Command::new(&cargo)
        .output()
        .expect_err("the program doesn't exist");
    let output = run(fuzz(&dir, &["fixture-panic"]).env("CARGO", &cargo));
    assert_eq!(stdout(&output), "");
    assert_eq!(
        std::str::from_utf8(&output.stderr).expect("the errors are UTF-8"),
        format!("error: couldn't start `cargo run`: {source}\n")
    );
    assert_eq!(output.status.code(), Some(1));
}
