//! `lunaferra-bytecode` will define Lunaferra's register bytecode: its instruction set, its
//! function prototypes, the format of precompiled chunks, and the verifier that checks a chunk
//! before it runs, as the [bytecode spec] describes.
//!
//! The crate holds no code yet. Task M2.1 of the [roadmap], which defines the instructions and
//! prototypes, starts it.
//!
